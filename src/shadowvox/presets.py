def genre_options(name, *, dry_has_backing=False):
    """根据曲风名构造完全独立的 Options，绕过五轴联动。"""
    from .pipeline import Options

    if name not in GENRE_PRESETS:
        raise ValueError(f'未知曲风预设：{name}')
    spec = GENRE_PRESETS[name]
    return Options(
        pitch_mode='register',
        octave='auto',
        mix=True,
        comparison=True,
        renderer=ENGINE,
        rhythm_mode='full',
        mix_space=1.0,
        fixed_master=True,
        dry_has_backing=bool(dry_has_backing),
        genre_preset=name,
        mix_profile=deepcopy(spec['profile']),
        **spec['options'],
    )
